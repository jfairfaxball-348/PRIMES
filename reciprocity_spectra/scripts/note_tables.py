"""Regenerate (--write) or verify (--check) the tables in NOTE_DRAFT.md from the results JSONs.

Every table between the markers in NOTE_DRAFT.md is produced here, so each quoted number traces
to a committed results file. Pure Python (json only).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
RES = HERE / 'results'
NOTE = HERE / 'NOTE_DRAFT.md'
START, END = '<!-- tables:start (generated by scripts/note_tables.py; do not edit) -->', '<!-- tables:end -->'


def load(name):
    return json.loads((RES / name).read_text())


def fmt(v, n=4):
    return f'{v:.{n}f}'


def tables():
    out = []
    a = load('phase1_2026-10-24.json')
    out += ['**Table 1. RS-S002 registered tests at X = 320000** (predictions committed at `0b77769`; '
            '`results/phase1_2026-10-24.json`).', '',
            '| family | D | statistic | value | registered criterion | outcome |', '|---|---:|---|---:|---|---|']
    for r in a['runs']:
        if r['mode'] == 'cubic':
            out.append(f"| cubic | {r['D']} | κ₃ | {fmt(r['kappa3'])} | [1.38, 1.47] | {r['predictions'][0]['outcome']} |")
            out.append(f"| cubic | {r['D']} | overlap − BBP prediction | {fmt(r['overlap_conj_gauss'] - r['bbp_predicted_overlap'])} "
                       f"| within ±0.03 | {r['predictions'][1]['outcome']} |")
        elif r['mode'] == 'quartic':
            out.append(f"| quartic | {r['D']} | θ/√D | {fmt(r['theta_normalized'])} | 0.166 ln X − 0.18 ± 0.05 "
                       f"(= {fmt(r['predicted_theta_normalized'])}) | {r['predictions'][0]['outcome']} |")
        else:
            out.append(f"| quadratic | {r['D']} | (2 − m₄) ln D | {fmt(r['quadratic_correction'])} | [1.0, 1.4] "
                       f"| {r['predictions'][0]['outcome']} |")
    b = load('phase1b_2026-10-24.json')
    out += ['', '**Table 2. RS-S003 registered tests (all FAIL; retained)** (`results/phase1b_2026-10-24.json`). '
            'Controls matched reciprocity only.', '',
            '| test | X | D | arithmetic | control | criterion | outcome |', '|---|---:|---:|---:|---:|---|---|']
    for r in b['sextic_runs']:
        out.append(f"| sextic σ₁/edge and excess | {r['X']} | {r['D']} | {fmt(r['sigma1_over_edge'])} | "
                   f"{fmt(r['control_sigma1_over_edge'])} | ≤ 1.02 and excess ≤ 0.02 | "
                   f"{'/'.join(p['outcome'] for p in r['predictions'])} |")
    for r in b['local_runs']:
        out.append(f"| {r['mode']} bulk gap ratio | {r['X']} | {r['D']} | {fmt(r['arithmetic']['mean_bulk_gap_ratio'])} | "
                   f"{fmt(r['control']['mean_bulk_gap_ratio'])} | difference ≤ 0.03 | {r['prediction']['outcome']} |")
    c = load('phase1c_2026-10-25.json')
    out += ['', '**Table 3. RS-S004 registered tests against the conjugation-matched null** (predictions at '
            f"`{c['prediction_commit']}`; `results/phase1c_2026-10-25.json`; control seed 0).", '',
            '| ID | family | X | D | value | outcome |', '|---|---|---:|---:|---:|---|']
    for r in c['registered']:
        for p in r['prediction_outcomes']:
            out.append(f"| {p['id']} | {r['mode']} | {r['X']} | {r['D']} | {fmt(p['value'])} | {p['outcome']} |")
    d = load('phase1d_2026-10-25.json')
    out += ['', '**Table 4. Sextic cluster (RS-7a)** (`results/phase1d_2026-10-25.json`; exploratory rows use the max of '
            'control seeds 0–2, the registered row seed 0).', '',
            '| X | D | σ₁/edge | values above control | family enrichment (top 8) | role |', '|---:|---:|---:|---:|---:|---|']
    for r in d['exploratory']:
        f = r['family_span_projection']
        ratio = sum(f['conj g6'][:8]) / sum(f['random_span'][:8])
        out.append(f"| {r['X']} | {r['D']} | {fmt(r['top_k_over_edge'][0])} | {r['multiplicity_above_max_control']} | "
                   f"{fmt(ratio, 2)} | EXPLORATORY |")
    r = d['registered']
    out.append(f"| {r['X']} | {r['D']} | {fmt(r['top_k_over_edge'][0])} | {r['multiplicity']} | "
               f"{fmt(r['family_enrichment_top8'], 2)} | REGISTERED: "
               f"{', '.join(p['id'] + ' ' + p['outcome'] for p in r['prediction_outcomes'])} |")
    e = load('phase1e_2026-10-25.json')
    out += ['', '**Table 5. Primary-class dichotomy (RS-7b)**: r_u = ‖C w_u‖/(√D‖w_u‖), w_u = conj(g̃6)(u/π)₆, '
            '"+" twists by u coprime to 3 (`results/phase1e_2026-10-25.json`).', '',
            '| X | D | N(u) ≤ | min r over ±primary u | max r over other associates | r₁ | max r, random vectors | role |',
            '|---:|---:|---:|---:|---:|---:|---:|---|']
    rows = []
    for run in e['runs'] + e['rayleigh_runs']:
        plus = [t for t in run['twists'] if t['sign'] == '+' and (t['u'][0] + t['u'][1]) % 3]
        pm = [t['r'] for t in plus if t['u'][1] % 3 == 0]
        other = [t['r'] for t in plus if t['u'][1] % 3]
        r1 = next(t['r'] for t in run['twists'] if t['u'] in ([1, 0], [-1, 0]) and t['sign'] == '+')
        role = run.get('classification', 'EXPLORATORY')
        if 'prediction_outcomes' in run:
            role = 'REGISTERED: ' + ', '.join(p['outcome'] for p in run['prediction_outcomes'])
        rows.append((run['X'], f"| {run['X']} | {run['D']} | {run['norm_max']} | {fmt(min(pm))} | {fmt(max(other))} | "
                     f"{fmt(r1)} | {fmt(max(run['random_phase_r']))} | {role} |"))
    out += [t for _, t in sorted(rows)]
    f = load('phase1f_2026-10-25.json')
    out += ['', '**Table 6. Associate sum rule and strength profile** (`results/phase1f_2026-10-25.json`).', '',
            '| X | ±primary mean r²−1 | other mean r²−1 | mean Σ over 6 associates of (r²−1) | exponent of N(u) |',
            '|---:|---:|---:|---:|---:|']
    for s in sorted(f['sum_rule'], key=lambda s: s['X']):
        out.append(f"| {s['X']} | {fmt(s['mean_pm_r2_minus_1'], 3)} | {fmt(s['mean_other_r2_minus_1'], 3)} | "
                   f"{fmt(s['mean_sum_r2_minus_1'], 3)} ± {fmt(s['sd_sum_r2_minus_1'], 3)} | "
                   f"{fmt(s['pm_powerlaw_exponent_in_N'], 3)} |")
    return '\n'.join(out)


def main():
    note = NOTE.read_text()
    head, rest = note.split(START)
    _, tail = rest.split(END)
    new = f'{head}{START}\n\n{tables()}\n\n{END}{tail}'
    if '--write' in sys.argv:
        NOTE.write_text(new)
    elif new != note:
        sys.exit('NOTE_DRAFT.md tables are out of date with the results JSONs')
    print('tables consistent' if '--write' not in sys.argv else 'tables written')


if __name__ == '__main__':
    main()
